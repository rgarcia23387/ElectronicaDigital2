/* Comandos que llegan de la Nucleo del juego por UART5 (PD2): buffer circular */
#define RX_SIZE 64
static volatile uint8_t rx_buf[RX_SIZE];
static volatile uint8_t rx_head = 0, rx_tail = 0;
static uint8_t rx_byte;

void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
  if (huart->Instance == UART5) {
    uint8_t next = (rx_head + 1) % RX_SIZE;
    if (next != rx_tail) { rx_buf[rx_head] = rx_byte; rx_head = next; }
    HAL_UART_Receive_IT(huart, &rx_byte, 1);
  }
}

void HAL_UART_ErrorCallback(UART_HandleTypeDef *huart)
{
  if (huart->Instance == UART5) {               /* ruido al conectar cables: se rearma */
    __HAL_UART_CLEAR_OREFLAG(huart);
    HAL_UART_Receive_IT(huart, &rx_byte, 1);
  }
}

/* TIM6: una muestra de audio por interrupcion (SYNTH_FS veces por segundo) */
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
  if (htim->Instance == TIM6) synth_sample_isr();
}
