void HAL_TIM_IC_CaptureCallback(TIM_HandleTypeDef *htim)
{
    if (htim->Instance == TIM2 && htim->Channel == HAL_TIM_ACTIVE_CHANNEL_1)
    {
        uint32_t valor_actual = HAL_TIM_ReadCapturedValue(htim, TIM_CHANNEL_1);

        if (!primera_captura)
        {
            /* primera captura: solo guardamos referencia, todavía no hay período */
            valor_anterior  = valor_actual;
            primera_captura = 1;
        }
        else
        {
            uint32_t diferencia;
            if (valor_actual > valor_anterior)
            {
                diferencia = valor_actual - valor_anterior;
            }
            else
            {
                /* el contador de 32 bits dio la vuelta (overflow) */
                diferencia = (0xFFFFFFFFu - valor_anterior) + valor_actual + 1u;
            }

            if (diferencia > 0)
            {
                frecuencia_hz = (float)TIMER_CLK_HZ / (float)diferencia;
                nueva_frecuencia_lista = 1;
            }
            valor_anterior = valor_actual;
        }
    }
}
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
    if (htim->Instance == TIM3)
    {
        HAL_GPIO_TogglePin(LED_500MS_GPIO_Port, LED_500MS_Pin);
    }
    else if (htim->Instance == TIM4)
    {
        HAL_GPIO_TogglePin(LED_2S_GPIO_Port, LED_2S_Pin);
    }
}
